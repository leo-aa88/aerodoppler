"""`make demo`: fully offline SYNTHETIC end-to-end run with diagnostic plots (SPEC §1 definition
of done (a), §13 exit criteria). Everything produced is labelled SYNTHETIC DEMO."""

from __future__ import annotations

import json
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

import numpy as np

from aerodoppler.audio.service import (
    ensure_spectrogram,
    ingest_recording,
    pick_event_pair,
    propose_events,
)
from aerodoppler.config import Settings
from aerodoppler.geo.coordinates import haversine_m
from aerodoppler.jobs.runner import run_search_inline
from aerodoppler.jobs.store import Store
from aerodoppler.models import QualitySettings, SearchMode, SearchRequest, SearchResult, unix_to_iso
from aerodoppler.validation.plots import plot_candidate_map, plot_spectrogram
from aerodoppler.validation.scenarios import ScenarioSpec, build_scenario


def run_demo(
    settings: Settings,
    out: Path,
    seed: int = 7,
    workers: int = 0,
    snr_db: float = 10.0,
    run_known_time: bool = True,
    log: Callable[[str], None] = print,
) -> dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    settings.ensure_dirs()
    store = Store(settings.db_path)
    t0 = time.time()
    spec = ScenarioSpec(name="demo", seed=seed, snr_db=snr_db)
    log(
        "[demo] building SYNTHETIC scenario (two propeller aircraft + distractors, synthetic DEM, retarded-time audio)…"
    )
    sc = build_scenario(spec, out / "scenario", settings.normalized_dir, settings.dem_dir)
    truth = sc.truth
    log(
        f"[demo] truth: lat {truth['observer_lat']:.5f} lon {truth['observer_lon']:.5f}, recording start {truth['recording_start_utc']} (hidden from Mode A)"
    )
    rec = ingest_recording(
        store,
        settings,
        sc.wav_path,
        owner_permission_confirmed=True,
        recording_date_utc=spec.date_utc,
        synthetic=True,
        notes="SYNTHETIC DEMO generated by `aerodoppler demo`",
    )
    spg = ensure_spectrogram(store, settings, rec.id)
    all_events = propose_events(store, settings, rec.id)
    events = pick_event_pair(all_events)
    log(f"[demo] {len(all_events)} proposals; using the two most credible, time-separated events")
    log(
        f"[demo] recording {rec.id}: {len(events)} auto-detected events: "
        + ", ".join(
            f"{e.id}[{e.audio_start_s:.0f}-{e.audio_end_s:.0f}s f0~{e.f0_prior:.1f}Hz]"
            for e in events
        )
    )
    summary: dict[str, Any] = {
        "label": "SYNTHETIC DEMO",
        "recording_id": rec.id,
        "truth": {
            k: truth[k]
            for k in ("observer_lat", "observer_lon", "recording_start_utc", "ground_elevation_m")
        },
        "events": [e.model_dump(exclude={"ridge_points"}) for e in events],
        "runs": {},
    }
    plot_spectrogram(
        spg,
        out / "spectrogram_detected_ridges.png",
        title="auto-detected ridge proposals",
        fmax=600,
        overlays=[
            {
                "t": [p.relative_t_s for p in e.ridge_points],
                "f": [p.frequency_hz for p in e.ridge_points],
                "label": f"{e.id} (h={e.ridge_harmonic})",
                "color": c,
            }
            for e, c in zip(events, ["cyan", "lime", "yellow", "white"], strict=False)
        ],
        synthetic=True,
    )
    if len(events) < 2:
        summary["abstention"] = "fewer than two events detected; Mode A impossible"
        return summary
    q = QualitySettings(workers=workers)
    # ---- Mode A: unknown clock time ----------------------------------------------------------
    log("[demo] Mode A (unknown time): searching flight pairs with Δt lock…")
    req_a = SearchRequest(
        mode=SearchMode.UNKNOWN_TIME,
        recording_id=rec.id,
        event_ids=[events[0].id, events[1].id],
        date_utc=spec.date_utc,
        bbox=spec.bbox,
        flight_dataset_ids=[sc.dataset.dataset_id],
        operator_authorized=True,
        quality_settings=q,
        seed=seed,
    )
    res_a = run_search_inline(
        store,
        settings,
        req_a,
        progress=lambda st, info: log(
            f"[demo:A] {st} {json.dumps({k: v for k, v in info.items() if k in ('n', 'best', 'done', 'total', 'elapsed_s')}, default=str)}"
        ),
    )
    summary["runs"]["mode_a"] = _summarize(res_a, truth, settings)
    _plots(res_a, truth, settings, out, "mode_a", spg, events)
    # ---- Mode B: known clock time with 60 s uncertainty, single event --------------------------
    if run_known_time:
        log(
            "[demo] Mode B (known time ±10 s, single event; note the along-track/mirror ambiguity of one straight flyby)…"
        )
        req_b = SearchRequest(
            mode=SearchMode.KNOWN_TIME,
            recording_id=rec.id,
            event_ids=[events[0].id],
            start_utc=unix_to_iso(truth["recording_start_unix"] + 4.0),
            start_uncertainty_s=10.0,
            bbox=spec.bbox,
            flight_dataset_ids=[sc.dataset.dataset_id],
            operator_authorized=True,
            quality_settings=q,
            seed=seed,
        )
        res_b = run_search_inline(
            store,
            settings,
            req_b,
            progress=lambda st, info: log(
                f"[demo:B] {st} {json.dumps({k: v for k, v in info.items() if k in ('n', 'best', 'done', 'total', 'elapsed_s')}, default=str)}"
            ),
        )
        summary["runs"]["mode_b"] = _summarize(res_b, truth, settings)
        _plots(res_b, truth, settings, out, "mode_b", spg, events[:1])
    summary["elapsed_s"] = round(time.time() - t0, 1)
    summary["outputs"] = sorted(str(p.relative_to(out)) for p in out.rglob("*.png"))
    (out / "demo_summary.json").write_text(json.dumps(summary, indent=2, default=str))
    for name, r in summary["runs"].items():
        log(
            f"[demo] {name}: abstained={r['abstained']} best error {r.get('top1_error_m')} m, score {r.get('top1_score')} ({r['score_label']}), inferred start {r.get('top1_inferred_start_utc')} (truth {truth['recording_start_utc']})"
        )
    return summary


def _summarize(res: SearchResult, truth: dict[str, Any], settings: Settings) -> dict[str, Any]:
    d: dict[str, Any] = {
        "run_id": res.run_id,
        "abstained": res.abstention.abstained,
        "abstention": res.abstention.model_dump(),
        "score_label": res.score_label,
        "stage_counters": [c.model_dump() for c in res.stage_counters],
        "warnings": res.warnings,
        "run_dir": str(settings.runs_dir / res.run_id),
    }
    if res.candidates:
        c = res.candidates[0]
        d.update(
            {
                "top1_error_m": round(
                    float(haversine_m(c.lat, c.lon, truth["observer_lat"], truth["observer_lon"])),
                    1,
                ),
                "top1_score": round(c.score_total, 3),
                "top1_inferred_start_utc": c.inferred_start_utc,
                "top1_flights": [s["icao24"] for s in c.extra["segments"]],
                "top1_f0_hz": [round(f, 2) for f in c.source_fundamental_hz_per_event],
                "top1_uncertainty_m": c.estimated_uncertainty_m,
                "top1_flags": c.flags,
                "all_errors_m": [
                    round(
                        float(
                            haversine_m(k.lat, k.lon, truth["observer_lat"], truth["observer_lon"])
                        ),
                        1,
                    )
                    for k in res.candidates
                ],
                "all_scores": [round(k.score_total, 3) for k in res.candidates],
            }
        )
    return d


def _plots(
    res: SearchResult, truth: dict[str, Any], settings: Settings, out: Path, tag: str, spg, events
) -> None:
    run_dir = settings.runs_dir / res.run_id
    # map: heatmap + tracks + best + truth
    heat = (run_dir / "heatmap.csv").read_text().strip().split("\n")[1:]
    lat = np.array([float(r.split(",")[0]) for r in heat]) if heat else np.empty(0)
    lon = np.array([float(r.split(",")[1]) for r in heat]) if heat else np.empty(0)
    sc = np.array([float(r.split(",")[4]) for r in heat]) if heat else np.empty(0)
    tracks = (
        json.loads((run_dir / "tracks.json").read_text())
        if (run_dir / "tracks.json").exists()
        else []
    )
    best = (res.candidates[0].lat, res.candidates[0].lon) if res.candidates else None
    err = (
        f" — top-1 error {float(haversine_m(best[0], best[1], truth['observer_lat'], truth['observer_lon'])):.0f} m"
        if best
        else " — abstained"
    )
    plot_candidate_map(
        out / f"{tag}_map.png",
        lat,
        lon,
        sc,
        [
            {
                "lat": t["lat"],
                "lon": t["lon"],
                "label": f"{t['icao24']} {t.get('type') or '?'}{' (used)' if t['used'] else ''}",
            }
            for t in tracks
        ],
        best,
        (truth["observer_lat"], truth["observer_lon"]),
        f"{tag}: score landscape, flight tracks, predicted vs true receiver{err}",
        synthetic=True,
        bbox=res.request.bbox.as_tuple() if res.request.bbox else None,
    )
    # observed vs predicted curves for the best candidate
    if res.candidates:
        curves = json.loads(
            (run_dir / "curves" / f"{res.candidates[0].candidate_id}.json").read_text()
        )
        overlays = []
        colors = ["cyan", "lime", "yellow", "orange", "magenta", "white"]
        for ev in curves["events"]:
            for h, f in ev["predicted_hz_by_harmonic"].items():
                overlays.append(
                    {
                        "t": ev["t_rel_s"],
                        "f": f,
                        "label": f"predicted {ev['segment_id'].split(':')[1]} h{h}"
                        if h == "1"
                        else None,
                        "color": colors[(int(h) - 1) % len(colors)],
                        "lw": 0.8,
                        "style": "--",
                    }
                )
            overlays.append(
                {
                    "t": ev["observed_ridge"]["t_rel_s"],
                    "f": ev["observed_ridge"]["frequency_hz"],
                    "label": f"observed ridge (h={ev['observed_ridge']['harmonic']})",
                    "color": "red",
                    "lw": 1.2,
                    "style": ":",
                }
            )
        plot_spectrogram(
            spg,
            out / f"{tag}_curves_best.png",
            title=f"{tag}: predicted (dashed) vs observed (dotted) Doppler curves at the top-1 location",
            fmax=600,
            overlays=overlays,
            synthetic=True,
        )
