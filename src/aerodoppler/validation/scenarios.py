"""Synthetic end-to-end scenarios (clearly labelled SYNTHETIC) for tests, the demo and the
synthetic benchmark. A scenario produces: flights (two audible propeller aircraft plus
distractors), an ADS-B-like dataset written through the normal ingestion path, a synthetic DEM,
the receiver truth, and a WAV generated by the independent simulator."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from aerodoppler.adsb.index import FlightDataset
from aerodoppler.adsb.ingest import import_samples_dataframe, samples_from_flight_samples
from aerodoppler.audio.decode import write_wav
from aerodoppler.audio.synthetic import (
    SyntheticFlight,
    SyntheticScene,
    flight_to_adsb_samples,
    straight_path,
    synthesize_scene,
    turning_path,
)
from aerodoppler.geo.altitude import ground_point_hae
from aerodoppler.geo.coordinates import LocalFrame
from aerodoppler.geo.dem import GeoTiffDEM, make_synthetic_dem
from aerodoppler.models import BBox, unix_to_iso
from aerodoppler.physics.propagation import speed_of_sound_mps


@dataclass
class ScenarioSpec:
    name: str = "demo"
    seed: int = 7
    observer_lat: float = 40.0
    observer_lon: float = -75.0
    bbox: BBox = field(
        default_factory=lambda: BBox(west=-75.25, south=39.82, east=-74.75, north=40.18)
    )
    date_utc: str = "2026-09-08"
    recording_start_rel_day_s: float = 14 * 3600 + 7 * 60 + 13.0  # unknown to Mode A
    duration_s: float = 1500.0
    fs: int = 8000
    temperature_c: float = 20.0
    snr_db: float = 10.0
    event_separation_s: float = 920.0
    n_distractors: int = 3
    hum: bool = True
    f0_a: float = 88.0
    f0_b: float = 112.0
    drift_b: float = 1.5e-5
    speed_a: float = 62.0
    speed_b: float = 74.0
    cpa_a_m: float = 1400.0
    cpa_b_m: float = 2300.0
    alt_a_m: float = 1100.0
    alt_b_m: float = 850.0
    heading_a: float = 75.0
    heading_b: float = 160.0
    b_turns: bool = True
    adsb_gap_in_b: bool = False


@dataclass
class ScenarioOutput:
    spec: ScenarioSpec
    wav_path: Path
    dem_path: Path
    dataset: FlightDataset
    truth: dict[str, Any]
    dem: GeoTiffDEM


def build_scenario(
    spec: ScenarioSpec, out_dir: Path, normalized_dir: Path, dem_dir: Path
) -> ScenarioOutput:
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(spec.seed)
    c = speed_of_sound_mps(spec.temperature_c)
    from aerodoppler.models import iso_to_unix

    day0 = iso_to_unix(spec.date_utc + "T00:00:00Z")
    t_rec0 = day0 + spec.recording_start_rel_day_s
    # DEM (synthetic rolling terrain) and observer height from it
    dem_path = make_synthetic_dem(
        spec.bbox,
        dem_dir / f"synthetic_{spec.name}.tif",
        base_elevation_m=120.0,
        amplitude_m=40.0,
        seed=spec.seed,
    )
    dem = GeoTiffDEM([dem_path], source="synthetic")
    ground = float(dem.elevation([spec.observer_lat], [spec.observer_lon]).elevation_m[0])
    obs_hae = float(ground_point_hae(ground, spec.observer_lat, spec.observer_lon, 1.5))
    frame = LocalFrame(spec.observer_lat, spec.observer_lon, obs_hae)
    # Flight A: straight flyby; CPA emission at recording-relative 190 s
    t_cpa_a = t_rec0 + 190.0
    # offset the CPA point perpendicular to heading at distance cpa_a (horizontal)
    ha = np.radians(spec.heading_a)
    perp_a = np.array([np.cos(ha), -np.sin(ha), 0.0])
    cpa_a = perp_a * spec.cpa_a_m + np.array([0.0, 0.0, spec.alt_a_m])
    fl_a = SyntheticFlight(
        "SYNA",
        "ad0001",
        t_cpa_a - 420,
        t_cpa_a + 420,
        straight_path(frame, t_cpa_a, cpa_a, spec.heading_a, spec.speed_a),
        spec.f0_a,
        0.0,
        (1.0, 0.65, 0.45, 0.3, 0.2),
        1.0,
        "C172",
    )
    # Flight B: delayed CPA ~ event_separation later; turning path
    t_cpa_b = t_cpa_a + spec.event_separation_s
    hb = np.radians(spec.heading_b)
    perp_b = np.array([np.cos(hb), -np.sin(hb), 0.0])
    cpa_b = perp_b * spec.cpa_b_m + np.array([0.0, 0.0, spec.alt_b_m])
    if spec.b_turns:
        # start 300 s before CPA, straight to CPA then a 1 deg/s turn beginning 40 s after CPA
        start = cpa_b - np.array([np.sin(hb), np.cos(hb), 0.0]) * spec.speed_b * 300.0
        path_b = turning_path(
            frame,
            t_cpa_b - 300.0,
            start,
            spec.heading_b,
            spec.speed_b,
            720.0,
            turn_rate_deg_s=1.0,
            turn_start_s=340.0,
            turn_duration_s=90.0,
            climb_rate_mps=0.5,
        )
    else:
        path_b = straight_path(frame, t_cpa_b, cpa_b, spec.heading_b, spec.speed_b)
    fl_b = SyntheticFlight(
        "SYNB",
        "ad0002",
        t_cpa_b - 300.0,
        t_cpa_b + 420.0,
        path_b,
        spec.f0_b,
        spec.drift_b,
        (1.0, 0.55, 0.4, 0.25),
        0.8,
        "P28A",
    )
    flights = [fl_a, fl_b]
    # Distractors: aircraft in the archive that are not audible (far / jets), including one
    # prop aircraft that passes the bbox between the events but far from the observer.
    for k in range(spec.n_distractors):
        off = np.array(
            [rng.uniform(-18000, 18000), rng.uniform(-18000, 18000), rng.uniform(900, 3500)]
        )
        if k == 0:
            off = np.array([9000.0, -7000.0, 1200.0])  # prop, between events, ~11 km away
        t_c = (
            t_rec0 + rng.uniform(100, spec.duration_s - 100)
            if k
            else t_cpa_a + 0.5 * spec.event_separation_s
        )
        hd = rng.uniform(0, 360)
        sp = rng.uniform(55, 95) if k == 0 else rng.uniform(120, 240)
        typ = "C182" if k == 0 else rng.choice(["A320", "B738", "E170", None])
        fl = SyntheticFlight(
            f"SYND{k}",
            f"ad01{k:02d}",
            t_c - 400,
            t_c + 400,
            straight_path(frame, t_c, off, hd, sp),
            100.0,
            0.0,
            (1.0,),
            0.0,
            typ,
            audible=False,
        )
        flights.append(fl)
    scene = SyntheticScene(
        spec.observer_lat,
        spec.observer_lon,
        obs_hae,
        frame,
        flights,
        t_rec0,
        spec.duration_s,
        spec.fs,
        c,
    )
    audio, truth = synthesize_scene(
        scene,
        rng,
        snr_db_at_cpa=spec.snr_db,
        hum_hz=60.0 if spec.hum else None,
        hum_level=0.5,
        gust_modulation=0.2,
    )
    wav_path = out_dir / f"synthetic_{spec.name}.wav"
    write_wav(wav_path, audio, spec.fs)
    # ADS-B-like samples through the normal ingestion path
    samples = []
    for fl in flights:
        gap = (
            (fl.t_start + 200, fl.t_start + 260)
            if (spec.adsb_gap_in_b and fl.name == "SYNB")
            else None
        )
        samples.extend(
            flight_to_adsb_samples(
                fl,
                rng,
                cadence_s=5.0,
                jitter_s=2.0,
                baro_offset_m=25.0,
                position_noise_m=6.0,
                dropout_fraction=0.05,
                gap=gap,
            )
        )
    df = samples_from_flight_samples(samples)
    ds_id = f"synthetic_{spec.name}_{spec.seed}"
    dataset = import_samples_dataframe(
        df,
        ds_id,
        normalized_dir,
        notes=[
            "SYNTHETIC DEMO DATA: generated by aerodoppler.validation.scenarios",
            f"scenario={spec.name}",
            f"seed={spec.seed}",
        ],
        extra_manifest={"request": {"date_utc": spec.date_utc, "bbox": spec.bbox.as_tuple()}},
    )
    truth.update(
        {
            "scenario": spec.name,
            "seed": spec.seed,
            "recording_start_utc": unix_to_iso(t_rec0),
            "recording_start_unix": t_rec0,
            "date_utc": spec.date_utc,
            "bbox": spec.bbox.as_tuple(),
            "ground_elevation_m": ground,
            "observer_hae_m": obs_hae,
            "event_a": {
                "icao24": fl_a.icao24,
                "t_cpa_emit_rel_s": 190.0,
                "f0_hz": spec.f0_a,
                "cpa_m": float(np.hypot(spec.cpa_a_m, spec.alt_a_m)),
            },
            "event_b": {
                "icao24": fl_b.icao24,
                "t_cpa_emit_rel_s": 190.0 + spec.event_separation_s,
                "f0_hz": spec.f0_b,
                "cpa_m": float(np.hypot(spec.cpa_b_m, spec.alt_b_m)),
            },
            "dataset_id": ds_id,
            "dem_path": str(dem_path),
            "wav_path": str(wav_path),
            "label": "SYNTHETIC DEMO",
        }
    )
    (out_dir / f"truth_{spec.name}.json").write_text(json.dumps(truth, indent=2, default=str))
    return ScenarioOutput(spec, wav_path, dem_path, dataset, truth, dem)
